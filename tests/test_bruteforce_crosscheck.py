"""Cross-check the graph verdict against exhaustive enumeration of serial
permutations on many small randomly generated snapshot histories.

Histories are generated by simulating snapshot-isolated execution, so every
recorded read is snapshot-correct by construction; the interesting question
is whether the history is serial-explainable.  For each history the audit's
graph verdict must agree with the brute-force permutation check.
"""

import random
import unittest

from tests.helpers import AuditCase, audit_doc

RNG = random.Random(20261118)


def gen_si_history(rng, n_txns, n_keys, max_ops=4):
    """Simulate SI execution under snapshot isolation.

    Returns a history document whose reads are all snapshot-correct.
    """
    initial = [{"key": k, "value": 0, "version_id": f"i{k}"}
               for k in range(n_keys)]
    committed = {k: [(0, f"i{k}", 0)] for k in range(n_keys)}  # key -> [(pos, vid, val)]
    commits = []
    txns = []
    pos = 0
    time_cursor = 0
    for t in range(n_txns):
        tid = f"T{t}"
        snapshot = rng.choice([c for c in range(pos + 1)])
        n_ops = rng.randint(1, max_ops)
        ops = []
        writes = {}
        seq = 0
        # random interleaving of reads and at most one write per key
        for _ in range(n_ops):
            key = rng.randrange(n_keys)
            if rng.random() < 0.45 and key not in writes:
                val = rng.randint(1, 9)
                if rng.random() < 0.15:
                    ops.append({"seq": seq, "type": "delete", "key": key})
                    writes[key] = ("delete", None)
                else:
                    ops.append({"seq": seq, "type": "put", "key": key,
                                "value": val})
                    writes[key] = ("put", val)
            else:
                # compute snapshot-correct read: own writes overlay snapshot
                if key in writes:
                    typ, val = writes[key]
                    if typ == "put":
                        ops.append({"seq": seq, "type": "point_read",
                                    "key": key, "found": True, "value": val})
                    else:
                        ops.append({"seq": seq, "type": "point_read",
                                    "key": key, "found": False})
                else:
                    vis = None
                    for (p, vid, val) in committed[key]:
                        if p <= snapshot:
                            vis = (vid, val)
                    if vis is None or vis[1] is None:
                        # never written, or visible version is a tombstone
                        ops.append({"seq": seq, "type": "point_read",
                                    "key": key, "found": False})
                    else:
                        ops.append({"seq": seq, "type": "point_read",
                                    "key": key, "found": True,
                                    "value": vis[1], "version_id": vis[0]})
            seq += 1
        start = time_cursor + rng.choice([0, 0, 1, 2])
        end = start + rng.choice([1, 2, 5])
        time_cursor = end
        txns.append({"txn_id": tid, "status": "committed",
                     "snapshot_pos": snapshot, "start_time": start,
                     "end_time": end, "operations": ops})
        if writes:
            pos += 1
            ws = []
            for key, (typ, val) in writes.items():
                pred = committed[key][-1][1]
                vid = f"v{pos}k{key}"
                w = {"key": key, "version_id": vid, "predecessor": pred}
                if typ == "delete":
                    w["tombstone"] = True
                    committed[key].append((pos, vid, None))
                else:
                    w["value"] = val
                    committed[key].append((pos, vid, val))
                ws.append(w)
            commits.append({"txn_id": tid, "commit_pos": pos, "writes": ws})
    return {
        "format": "snapshot-history/1",
        "initial_state": initial,
        "commit_log": {"first_commit_pos": 1 if commits else None,
                       "last_commit_pos": pos if commits else None,
                       "complete": True, "commits": commits},
        "transactions": txns,
    }


class BruteForceCrossCheckTest(AuditCase):
    def test_random_small_histories_agree(self):
        rng = random.Random(424242)
        n_valid = n_invalid = 0
        for case in range(60):
            n_txns = rng.randint(2, 6)
            n_keys = rng.randint(1, 3)
            doc = gen_si_history(rng, n_txns, n_keys)
            result, store = audit_doc(doc, want_bruteforce=True)
            self.addCleanup(store.close)
            self.assertEqual(result["anomalies_total"], 0,
                             f"case {case}: generated history has "
                             f"unexpected read anomalies: "
                             f"{result['anomalies'][:2]}")
            self.assertEqual(result["gaps_total"], 0,
                             f"case {case}: unexpected gaps: "
                             f"{result['gaps'][:3]}")
            self.assertIn(result["verdict"], ("valid", "invalid"))
            bf = result["bruteforce"]
            self.assertTrue(
                bf["agrees_with_graph"],
                f"case {case}: graph={result['verdict']} but "
                f"bruteforce={bf['verdict']}")
            if result["verdict"] == "valid":
                n_valid += 1
            else:
                n_invalid += 1
                self.assertTrue(
                    result["graph"]["cycle"]["independently_verified"])
        # the generator must produce both outcomes to make the check meaningful
        self.assertGreater(n_valid, 0)
        self.assertGreater(n_invalid, 0)

    def test_permutation_replay_checks_version_order_and_realtime(self):
        # hand-built case where only one permutation respects version order
        # and real time; brute force must find exactly the valid orders
        from snapshot_audit.bruteforce import brute_force
        from tests.helpers import HistoryBuilder, put_op, read_op
        b = HistoryBuilder()
        b.init(1, 0, "ix")
        b.commit("T1", 1, [(1, "x1", "ix", 1)])
        b.commit("T2", 2, [(1, "x2", "x1", 2)])
        b.txn("T1", 0, 1, 2, [put_op(0, 1, 1)])
        b.txn("T2", 1, 3, 4, [put_op(0, 1, 2)])
        b.txn("R", 2, 10, 20, [read_op(0, 1, 2, "x2")])
        result, store = audit_doc(b.doc())
        self.addCleanup(store.close)
        ok, order, _ = brute_force(store)
        self.assertTrue(ok)
        self.assertLess(order.index("T1"), order.index("T2"))
        self.assertLess(order.index("T2"), order.index("R"))


if __name__ == "__main__":
    unittest.main()
