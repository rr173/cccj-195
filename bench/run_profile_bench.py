#!/usr/bin/env python3
"""Workload-profile scale benchmark.

Records the resource guarantees of ``profile`` / ``verify-profile``:

* input record count, end-point events processed and emitted segments;
* peak RSS and wall time of the profile stage;
* a sparse single-interval int64 case proving cost grows with the number of
  end points/records, never with key-domain width.

Each configuration runs in a fresh subprocess so RSS is per-run.  Results are
appended as a markdown table (default: bench/PROFILE_BENCH.md).

Reproduce:
    python3 bench/run_profile_bench.py
    python3 bench/run_profile_bench.py --quick
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)


def _gen_scale(out, txns):
    gen = os.path.join(ROOT, "bench", "gen_scale.py")
    r = _run([sys.executable, gen, "--out", out, "--txns", str(txns),
              "--keys", "500", "--reads", "3", "--ranges", "2",
              "--range-width", "40", "--writes", "1", "--seed", "7"])
    if r.returncode != 0:
        raise RuntimeError(f"gen failed: {r.stderr}")


def profile_config(name, input_kind, input_path, window_width=10.0):
    out_json = os.path.join(os.path.dirname(input_path.rstrip(os.sep)),
                            "profile.json")
    r = _run([sys.executable, "-m", "snapshot_audit", "profile",
              "--input-dir" if input_kind == "dir" else "--input",
              input_path, "--window-width", str(window_width),
              "--top-n", "25", "--out", out_json])
    if r.returncode not in (0, 2):
        raise RuntimeError(f"profile failed for {name}: {r.stderr}")
    with open(out_json) as fh:
        prof = json.load(fh)
    vr = _run([sys.executable, "-m", "snapshot_audit", "verify-profile",
               "--profile", out_json])
    verified = vr.returncode == 0
    s, rt = prof["stats"], prof["runtime_stats"]
    return {
        "config": name,
        "status": prof["status"],
        "input_records": s["input_records"],
        "heat_events": s["heat_events_processed"],
        "scan_intervals": s["scan_intervals_processed"],
        "endpoint_events": s["endpoint_events_processed"],
        "segments": s["segments_emitted"],
        "windows": prof["windowing"]["window_count"],
        "wall_ms": rt["wall_time_ms_exact"],
        "rss_mb": round(rt["rss_bytes_exact"] / 1e6, 1),
        "verify_ok": verified,
    }


def sparse_int64_case(tmp):
    # one full int64-wide interval plus two wide neighbors: only 6 end-point
    # events exist, yet the domain spans all 2^64 integer keys
    lo, hi = -(2 ** 63), 2 ** 63 - 1
    doc = {
        "format": "snapshot-history/1", "initial_state": [],
        "commit_log": {"first_commit_pos": None, "last_commit_pos": None,
                       "complete": True, "commits": []},
        "transactions": [{
            "txn_id": "S1", "status": "committed", "snapshot_pos": 0,
            "start_time": 0, "end_time": 10,
            "operations": [
                {"seq": 0, "type": "range_read", "lo": lo, "hi": hi,
                 "entries": [], "complete": True},
                {"seq": 1, "type": "range_read", "lo": -5, "hi": 5,
                 "entries": [], "complete": True},
                {"seq": 2, "type": "range_read", "lo": 5, "hi": hi,
                 "entries": [], "complete": True},
            ]}],
    }
    path = os.path.join(tmp, "sparse.json")
    with open(path, "w") as fh:
        json.dump(doc, fh)
    row = profile_config("sparse-int64", "file", path)
    # the invariant the benchmark exists to pin:
    assert row["endpoint_events"] == 6, row
    assert row["segments"] <= row["endpoint_events"], row
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out",
                    default=os.path.join(ROOT, "bench", "PROFILE_BENCH.md"))
    args = ap.parse_args()

    sizes = [300, 2000] if args.quick else [300, 2000, 10000]
    rows = []
    tmp = tempfile.mkdtemp(prefix="prof-bench-")
    try:
        for n in sizes:
            hist = os.path.join(tmp, f"h{n}")
            _gen_scale(hist, n)
            rows.append(profile_config(f"scale-{n}", "dir", hist))
        rows.append(sparse_int64_case(tmp))
    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)

    cols = ["config", "status", "input_records", "heat_events",
            "scan_intervals", "endpoint_events", "segments", "windows",
            "wall_ms", "rss_mb", "verify_ok"]
    lines = [
        "# Workload-profile benchmark results", "",
        "Generated by `python3 bench/run_profile_bench.py` (fresh subprocess "
        "per config; RSS = peak resident set of the profile process).", "",
        "| " + " | ".join(cols) + " |",
        "|" + "|".join("---" for _ in cols) + "|",
    ]
    for r in rows:
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    lines += [
        "", "## Notes", "",
        "- `endpoint_events` is exactly 2x the number of completed range "
        "scans; `segments` never exceeds the number of distinct end points, "
        "regardless of interval width.",
        "- `sparse-int64` covers the entire int64 key domain "
        "(-2^63..2^63-1) with three intervals and only six end-point events: "
        "cost grows with end points/records, never with key-domain width.",
        "- Heat counters are aggregated in bounded memory and spilled to "
        "SQLite above the in-memory cap; no interval is expanded into "
        "per-key records.",
        "- `verify_ok` means `verify-profile` independently recomputed every "
        "signed field from the raw history.",
        "",
    ]
    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))
    for r in rows:
        print(f"{r['config']}: records={r['input_records']} "
              f"endpoints={r['endpoint_events']} segments={r['segments']} "
              f"wall={r['wall_ms']}ms rss={r['rss_mb']}MB "
              f"verify={r['verify_ok']}")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
