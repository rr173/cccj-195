#!/usr/bin/env python3
"""Run the auditor over generated scale histories and record the index plan,
candidate-comparison counters and peak RSS.

Each configuration runs in a fresh subprocess so RSS is per-run.  Results
are written as a markdown table (default: bench/BENCH.md).

Reproduce:
    python3 bench/run_bench.py            # bounded default set
    python3 bench/run_bench.py --quick    # smallest set only
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CONFIGS = [
    # (name, txns, keys, reads, ranges, range_width, writes, skew_pairs,
    #  extra_gen_args)
    ("small-valid", 300, 100, 3, 1, 40, 1, 0,
     ["--snapshot-mode", "current", "--no-overlap"]),
    ("small-skew", 300, 100, 3, 1, 40, 1, 40, []),
    ("mid-valid", 2000, 500, 3, 1, 40, 1, 0,
     ["--snapshot-mode", "current", "--no-overlap"]),
    ("mid-skew", 2000, 500, 3, 1, 40, 1, 300, []),
    ("large-valid", 10000, 2000, 4, 2, 60, 2, 0,
     ["--snapshot-mode", "current", "--no-overlap"]),
    ("large-skew", 10000, 2000, 4, 2, 60, 2, 1500, []),
]

QUICK = [CONFIGS[0], CONFIGS[1]]


def run_config(cfg, keep_dirs=False):
    (name, txns, keys, reads, ranges, width, writes, skew, extra) = cfg
    tmp = tempfile.mkdtemp(prefix=f"bench-{name}-")
    hist = os.path.join(tmp, "hist")
    gen = subprocess.run(
        [sys.executable, os.path.join(ROOT, "bench", "gen_scale.py"),
         "--out", hist, "--txns", str(txns), "--keys", str(keys),
         "--reads", str(reads), "--ranges", str(ranges),
         "--range-width", str(width), "--writes", str(writes),
         "--skew-pairs", str(skew), "--seed", "7"] + extra,
        capture_output=True, text=True, cwd=ROOT)
    if gen.returncode != 0:
        raise RuntimeError(f"gen failed for {name}: {gen.stderr}")
    out_json = os.path.join(tmp, "result.json")
    audit = subprocess.run(
        [sys.executable, "-m", "snapshot_audit", "audit",
         "--input-dir", hist, "--out", out_json],
        capture_output=True, text=True, cwd=ROOT)
    if audit.returncode not in (0, 1, 2):
        raise RuntimeError(f"audit failed for {name}: {audit.stderr}")
    with open(out_json) as fh:
        result = json.load(fh)
    s = result["stats"]
    row = {
        "config": name,
        "verdict": result["verdict"],
        "txns": txns,
        "versions": s.get("versions", 0),
        "point_reads": s.get("point_reads_checked", 0),
        "range_reads": s.get("range_reads_checked", 0),
        "version_lookups": s.get("version_lookups", 0),
        "range_keys_scanned": s.get("range_keys_scanned", 0),
        "edge_candidates": s.get("edge_candidates", 0),
        "edges_emitted": s.get("edges_emitted", 0),
        "realtime_edges": s.get("realtime_edges", 0),
        "wall_ms": s.get("wall_time_ms", 0),
        "rss_mb": round(s.get("rss_bytes", 0) / 1e6, 1),
    }
    if not keep_dirs:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)
    return row, result.get("index_plan", [])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", default=os.path.join(ROOT, "bench", "BENCH.md"))
    ap.add_argument("--keep-dirs", action="store_true")
    args = ap.parse_args()

    configs = QUICK if args.quick else CONFIGS
    rows = []
    index_plan = None
    for cfg in configs:
        row, plan = run_config(cfg, keep_dirs=args.keep_dirs)
        index_plan = plan
        rows.append(row)
        print(f"{row['config']}: verdict={row['verdict']} "
              f"edges={row['edges_emitted']} wall={row['wall_ms']}ms "
              f"rss={row['rss_mb']}MB")

    cols = ["config", "verdict", "txns", "versions", "point_reads",
            "range_reads", "version_lookups", "range_keys_scanned",
            "edge_candidates", "edges_emitted", "realtime_edges",
            "wall_ms", "rss_mb"]
    lines = ["# Benchmark results", "",
             "Generated by `python3 bench/run_bench.py` (per-config fresh "
             "subprocess; RSS = peak resident set of the audit process).", "",
             "| " + " | ".join(cols) + " |",
             "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    lines += ["", "## Index plan (as reported by the auditor)", ""]
    lines += [f"- {p}" for p in (index_plan or [])]
    lines += ["", "## Notes", "",
              "- `edge_candidates` counts the indexed visible/successor "
              "version probes issued for reads (2 per key touched by a "
              "read); `range_keys_scanned` counts versioned keys visited "
              "inside scanned intervals - intervals are never expanded "
              "over the int64 domain.",
              "- `realtime_edges` are emitted by a sorted sweep "
              "(O(n log n) candidate comparisons), not an n x n scan.",
              "- skew configs inject write-skew pairs; the auditor "
              "reports `invalid` with a verified cycle witness.",
              ""]
    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
